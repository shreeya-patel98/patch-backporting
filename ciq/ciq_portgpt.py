#!/usr/bin/env python3
"""ciq-portgpt: backport an upstream kernel fix to a CIQ branch with PortGPT + Claude.

  ciq_portgpt.py <upstream-sha> <ciq-branch> --cve CVE-X --jira VULN-N

Steps:
  1. Resolve the upstream fix, its parent and the target branch in kernel-src-tree.
  2. Prepare an isolated git worktree (PortGPT runs checkout/reset/clean -fdx there).
  3. Write a per-run dataset dir with build.sh (compiles touched objects inside a
     Rocky container matching the branch) and the PortGPT config.
  4. Run PortGPT (Claude). On success it writes backport.patch.
  5. Commit the result on {shreeya}_<branch>_<CVE> in CIQ format; if the patch
     differs from upstream, ask Claude to draft the upstream-diff note.
"""

import argparse
import os
import re
import shlex
import subprocess
import sys
import textwrap
from pathlib import Path

import yaml

HERE = Path(__file__).resolve().parent
PORTGPT_SRC = HERE.parent / "src"
VENV_PY = HERE.parent / ".venv" / "bin" / "python"
CI_REGISTRY = "pulp.prod.ciq.dev/ciq/cicd/lts-images"


def git(repo, *args, check=True):
    r = subprocess.run(["git", "-C", str(repo), *args], capture_output=True, text=True)
    if check and r.returncode:
        sys.exit(f"git {' '.join(args)} failed:\n{r.stderr}")
    return r.stdout.strip()


def el_flavor(repo, ref):
    mk = git(repo, "show", f"{ref}:Makefile")
    major = int(re.search(r"^VERSION = (\d+)", mk, re.M).group(1))
    return "el8" if major == 4 else "el9"  # TODO: el10 image for 6.x (rlc-10)


BUILD_SH = """#!/bin/bash
# Generated by ciq_portgpt.py. Runs with cwd = PortGPT worktree (patch applied).
# Compiles only the objects touched by the patch, inside a {flavor} container,
# out-of-tree so `git clean -fdx` in the worktree doesn't wipe the build.
set -o pipefail
SRC="$(pwd)"
OUT={out}
mkdir -p "$OUT"
FILES=$(git diff --name-only HEAD | grep '\\.c$')
if [ -z "$FILES" ]; then
  # header-only change: compile every .c in the dirs of touched headers
  for d in $(git diff --name-only HEAD | grep '\\.h$' | xargs -r -n1 dirname | sort -u); do
    FILES="$FILES $(ls $d/*.c 2>/dev/null)"
  done
fi
OBJS=$(for f in $FILES; do echo "${{f%.c}}.o"; done)
[ -z "$OBJS" ] && {{ echo "No C objects to compile."; exit 0; }}
podman run --rm --security-opt label=disable -v "$SRC":/src -v "$OUT":/out -w /src \\
  {image} bash -c '
    if [ ! -f /out/.config ]; then
      # same config search order as kernel-container-build/container/kernel_build.sh
      VER=$(make -s kernelversion 2>/dev/null | cut -d- -f1)
      for c in ciq/configs/kernel-x86_64.config configs/kernel-x86_64.config \\
               configs/kernel-x86_64-rhel.config configs/kernel-$VER-x86_64.config \\
               configs/kernel-${{VER%.*}}.0-x86_64.config; do
        [ -f "$c" ] && {{ cp "$c" /out/.config; break; }}
      done
      [ -f /out/.config ] || {{ echo "BUILD-SETUP: no x86_64 config found"; exit 3; }}
      make -s O=/out olddefconfig >/dev/null || exit 3
    fi
    fail=0
    for o in '"$(echo $OBJS)"'; do
      log=$(make -s O=/out -j{jobs} KCFLAGS=-Wno-error "$o" 2>&1); rc=$?
      if [ $rc -ne 0 ] && grep -q "No rule to make target .$o." <<<"$log"; then
        echo "SKIPPED $o: not enabled in this kernel config (not shipped, cannot compile-check)"
      elif [ $rc -ne 0 ]; then
        echo "$log"; fail=1
      else
        echo "OK $o"
      fi
    done
    exit $fail
  ' > "$OUT/last-build.log" 2>&1
rc=$?
if [ $rc -ne 0 ]; then
  grep -E "BUILD-SETUP|SKIPPED" "$OUT/last-build.log"
  # keep feedback to the model short: errors with a little context
  grep -E -B2 -A6 'error:|Error [0-9]' "$OUT/last-build.log" | head -120
  exit $rc
fi
grep -E "^(OK|SKIPPED) " "$OUT/last-build.log"
"""

UPSTREAM_DIFF_PROMPT = """You are writing the `upstream-diff` note for a CIQ kernel backport commit.

Upstream commit {sha}:
<upstream_patch>
{upstream}
</upstream_patch>

Backported patch applied to CIQ branch {branch}:
<backport_patch>
{backport}
</backport_patch>

Write the note body only (no "upstream-diff" prefix). Rules:
- A few short lines, plain text, max ~72 chars per line.
- Say concretely what differs from upstream and why (e.g. context drift,
  function renamed in this kernel, hunk omitted because code is absent).
- If adapted code came from a specific upstream commit, name it.
- If the only differences are line offsets/whitespace context, reply exactly: NONE
"""


def draft_upstream_diff(model, sha, branch, upstream, backport):
    import anthropic

    client = anthropic.Anthropic()
    resp = client.messages.create(
        model=model,
        max_tokens=4000,
        thinking={"type": "adaptive"},
        output_config={"effort": "low"},
        messages=[{"role": "user", "content": UPSTREAM_DIFF_PROMPT.format(
            sha=sha, branch=branch, upstream=upstream, backport=backport)}],
    )
    if resp.stop_reason == "refusal":
        return "TODO: describe differences from upstream (model declined)"
    return "".join(b.text for b in resp.content if b.type == "text").strip()


def strip_diff_noise(patch):
    """Drop index/@@ line numbers so pure offset changes compare equal."""
    keep = []
    for line in patch.splitlines():
        if line.startswith(("index ", "diff --git")):
            continue
        if line.startswith("@@"):
            line = "@@"
        keep.append(line)
    return "\n".join(keep)


def build_commit_message(repo, sha, cve, jira, upstream_diff, cve_tag):
    subject = git(repo, "log", "-1", "--format=%s", sha)
    author = git(repo, "log", "-1", "--format=%an <%ae>", sha)
    body = git(repo, "log", "-1", "--format=%b", sha)
    signer = git(repo, "config", "user.name") + " <" + git(repo, "config", "user.email") + ">"

    hdr = [f"jira {jira}", f"{cve_tag} {cve}", f"commit-author {author}", f"commit {sha}"]
    if upstream_diff:
        lines = textwrap.wrap(" ".join(upstream_diff.split()), 58) or [upstream_diff]
        hdr.append("upstream-diff " + lines[0])
        hdr += [" " * 14 + l for l in lines[1:]]

    # Upstream trailers get tab-indented, matching existing CIQ commits.
    out_body = []
    for line in body.splitlines():
        if re.match(r"^[A-Za-z-]+: ", line) and not line.startswith("\t"):
            out_body.append("\t" + line)
        else:
            out_body.append(line)
    return (f"{subject}\n\n" + "\n".join(hdr) + "\n\n" + "\n".join(out_body).rstrip()
            + f"\n(cherry picked from commit {sha})\n\tSigned-off-by: {signer}\n")


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("sha", help="upstream fix commit (must exist in kernel-src-tree, e.g. on origin/kernel-mainline)")
    ap.add_argument("branch", help="CIQ target branch, e.g. ciqlts9_6")
    ap.add_argument("--cve", required=True)
    ap.add_argument("--jira", required=True, help="VULN-NNNN")
    ap.add_argument("--cve-tag", default="cve", choices=["cve", "cve-bf", "cve-pre"])
    ap.add_argument("--target", help="target commit (default: origin/<branch>)")
    ap.add_argument("--repo", default=str(Path.home() / "ciq/kernel-src-tree"))
    ap.add_argument("--work", default=str(Path.home() / "ciq/portgpt-work"))
    ap.add_argument("--model", default="claude-opus-5-5")
    ap.add_argument("--effort", default="medium", choices=["low", "medium", "high", "xhigh", "max"])
    ap.add_argument("--max-cost", type=float, default=3.0,
                    help="hard USD cap for the whole PortGPT run (default 3.0)")
    ap.add_argument("--max-iter", type=int, default=15,
                    help="max agent steps per conflicting hunk (default 15)")
    ap.add_argument("--branch-prefix", default="{shreeya}_")
    ap.add_argument("--fresh", action="store_true", help="discard previous results for this run")
    ap.add_argument("--no-commit", action="store_true", help="stop after producing backport.patch")
    a = ap.parse_args()

    repo, work = Path(a.repo), Path(a.work)
    if git(repo, "cat-file", "-t", a.sha, check=False) != "commit":
        sys.exit(f"{a.sha} not found in {repo}. Try: git -C {repo} fetch origin kernel-mainline")
    sha = git(repo, "rev-parse", a.sha)
    parent = git(repo, "rev-parse", f"{sha}^")
    target = git(repo, "rev-parse", a.target or f"origin/{a.branch}")
    # Use the same builder image as kernel CI: each branch names it in
    # .container_build_image (see kernel-container-build/build_kernel.sh).
    ci_img = git(repo, "show", f"{target}:.container_build_image", check=False).strip()
    if ci_img:
        flavor = ci_img
        image = f"{CI_REGISTRY}/{ci_img}" + ("" if ":" in ci_img else ":latest")
        if subprocess.run(["podman", "image", "exists", image]).returncode:
            print(f"[ciq-portgpt] pulling CI image {image}")
            if subprocess.run(["podman", "pull", "-q", image]).returncode:
                sys.exit(f"Could not pull {image}")
    else:  # fallback for branches without the CI file
        flavor = el_flavor(repo, target)
        image = f"localhost/ciq-portgpt-build:{flavor}"
        print(f"[ciq-portgpt] no .container_build_image on target; falling back to {image}")
        if subprocess.run(["podman", "image", "exists", image]).returncode:
            sys.exit(f"Missing build image {image}; build it from {HERE/'containers'}")

    # 1. isolated worktree
    wt = work / "kst"
    if not (wt / ".git").exists():
        work.mkdir(parents=True, exist_ok=True)
        git(repo, "worktree", "add", "--detach", str(wt), target)
    if git(wt, "status", "--porcelain", "--untracked-files=no"):
        git(wt, "reset", "--hard")

    # 2. run dir with build.sh + config
    run = work / "runs" / f"{a.branch}-{a.cve}"
    run.mkdir(parents=True, exist_ok=True)
    if a.fresh:
        for stale in ("backport.patch", "UPSTREAM_DIFF"):
            (run / stale).unlink(missing_ok=True)
    (run / "build.sh").write_text(BUILD_SH.format(
        flavor=flavor, image=image, jobs=os.cpu_count(),
        out=shlex.quote(str(work / f"build-{a.branch}-{target[:12]}"))))
    cfg = {
        "project": "kernel", "project_url": "https://github.com/ctrliq/kernel-src-tree",
        "new_patch": sha, "new_patch_parent": parent, "target_release": target,
        "tag": a.cve, "sanitizer": "", "error_message": "",
        "provider": "anthropic", "anthropic_model": a.model, "effort": a.effort,
        "max_cost": a.max_cost, "max_iter_hunk": a.max_iter, "max_iter_patch": max(5, a.max_iter * 2 // 3),
        "project_dir": str(wt) + "/", "patch_dataset_dir": str(run) + "/",
    }
    cfg_path = run / "config.yml"
    cfg_path.write_text(yaml.safe_dump(cfg, sort_keys=False))

    print(f"[ciq-portgpt] {sha[:12]} -> {a.branch} ({target[:12]}, {flavor}), model {a.model}/{a.effort}, cap ${a.max_cost:.2f}")
    print(f"[ciq-portgpt] run dir: {run}")

    # 3. PortGPT (skipped if this run already produced a validated patch)
    patch_file = run / "backport.patch"
    r = subprocess.CompletedProcess([], 0)
    if patch_file.exists():
        print("[ciq-portgpt] reusing existing validated patch (use --fresh to redo)")
    else:
        r = subprocess.run([str(VENV_PY), "backporting.py", "--config", str(cfg_path), "--debug"],
                           cwd=PORTGPT_SRC)
    if r.returncode or not patch_file.exists():
        sys.exit(f"[ciq-portgpt] PortGPT did not produce a validated patch. Logs: {PORTGPT_SRC.parent/'logs'}")
    print(f"[ciq-portgpt] validated patch: {patch_file}")
    notes = run / "REVIEW_NOTES"
    if notes.exists() and notes.read_text().strip():
        print("[ciq-portgpt] reviewer notes (function-anchor check):")
        for n in notes.read_text().strip().splitlines():
            print(f"    - {n}")
    if a.no_commit:
        return

    # 4. commit in CIQ format
    upstream = git(repo, "show", "--format=", sha)
    backport = patch_file.read_text()
    upstream_diff = None
    if strip_diff_noise(upstream) != strip_diff_noise(backport):
        print("[ciq-portgpt] patch differs from upstream; drafting upstream-diff with Claude")
        note_file = run / "UPSTREAM_DIFF"
        if note_file.exists():  # reuse a draft from an earlier attempt (no extra tokens)
            note = note_file.read_text()
        else:
            note = draft_upstream_diff(a.model, sha, a.branch, upstream, backport)
            note_file.write_text(note)
        upstream_diff = None if note.strip() == "NONE" else note

    work_branch = f"{a.branch_prefix}{a.branch}_{a.cve}"
    # PortGPT leaves its validated patch applied (plus copied scripts) in the worktree.
    git(wt, "reset", "-q", "--hard")
    git(wt, "clean", "-q", "-fdx")
    git(wt, "checkout", "-q", "-B", work_branch, target)
    git(wt, "apply", "--index", str(patch_file))
    msg = build_commit_message(repo, sha, a.cve, a.jira, upstream_diff, a.cve_tag)
    (run / "COMMIT_MSG").write_text(msg)
    git(wt, "commit", "-q", "-F", str(run / "COMMIT_MSG"))
    print(f"[ciq-portgpt] committed on {work_branch} in {wt}:\n")
    print(git(wt, "log", "-1", "--stat"))
    print("\nReview the upstream-diff wording before pushing.")


if __name__ == "__main__":
    main()
